import { readFile, writeFile, mkdir } from 'node:fs/promises';

const sourcePath = process.argv[2];
if (!sourcePath) throw new Error('Pass the SVG generated by flycran/github-gravity.');
const source = await readFile(sourcePath, 'utf8');
if (!source.includes('<animateTransform') || !source.includes('data-date=')) {
  throw new Error('Expected an animated GitHub Gravity SVG.');
}

// Keep the upstream physics and contribution data; add looping and theme variants.
const days = [...source.matchAll(/<g data-date="([^"]+)">([\s\S]*?)<\/g>/g)];
if (!days.length) throw new Error('No contribution days were generated.');
const still = days.map(([, date, body]) => {
  const frames = body.match(/values="([^"]+)"/)[1].split(';');
  const position = frames[Math.floor(frames.length * 0.2)].replace(',', ' ');
  const shape = body.replace(/<animateTransform[\s\S]*?\/>/, '');
  return `<g transform="translate(${position})"><title>${date}</title>${shape}</g>`;
}).join('\n');
const motion = days.map(([group, date]) => group
  .replace(`<g data-date="${date}">`, `<g data-date="${date}"><title>${date}</title>`)
  .replace('fill="freeze"', 'repeatCount="indefinite"'))
  .join('\n');
const text = source.slice(source.lastIndexOf('<g transform='), source.lastIndexOf('</svg>'));
const palettes = {
  dark: ['#182334', '#174579', '#2488d1', '#55b6f0', '#a5e6ff'],
  light: ['#edf2f8', '#a7d5fc', '#5aa8eb', '#2676c6', '#124a8a'],
};
const original = ['#ebedf0', '#9be9a8', '#40c463', '#30a14e', '#216e39'];
await mkdir('assets/contributions', { recursive: true });
for (const [theme, colors] of Object.entries(palettes)) {
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="900" height="450" viewBox="0 0 900 450" role="img" aria-labelledby="title description">
<title id="title">Tint Aung Khant — contributions in motion</title>
<desc id="description">${days.length} active days from the past year's public GitHub contribution calendar. Each dot is an active day, colored by contribution intensity. Physics animation generated by flycran/github-gravity, refreshed daily.</desc>
<style>
.still { display: none; }
@media (prefers-reduced-motion: reduce) { .motion { display: none; } .still { display: inline; } }
</style>
<g class="motion">${motion}</g>
<g class="still">${still}</g>
${text}
</svg>\n`;
  original.forEach((color, index) => { svg = svg.replaceAll(color, colors[index]); });
  svg = svg.replaceAll('#79c0ff', theme === 'dark' ? '#79c0ff' : '#0969da');
  await writeFile(`assets/contributions/gravity-${theme}.svg`, svg);
}
console.log(`Created looping light and dark animations from ${days.length} active contribution days.`);
